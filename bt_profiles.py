import re

_NAME_RE = [(re.compile(p, re.IGNORECASE), v, plat, cls) for (p, v, plat, cls) in NAME_PATTERNS]


def normalize_mac(address):
    """'AA-BB-CC-DD-EE-FF' / 'AA:BB:...' -> lowercase colon form (or '')."""
    if not address:
        return ""
    a = address.strip().replace("-", ":").lower()
    return a


def is_randomized_mac(address):
    """Locally-administered bit set -> private/randomized MAC (Android 10+/iOS 14+)."""
    a = normalize_mac(address)
    if len(a) < 8:
        return False
    nibble = a[1]
    return nibble in "26ae"


def oui_vendor(address):
    """Look up vendor from the first 3 MAC octets."""
    a = normalize_mac(address)
    if len(a) < 8:
        return None
    return OUI_VENDOR.get(a[:8])


def classify_by_name(name):
    """Classify using the broadcast name. Returns (vendor, platform, device_class) or None."""
    if not name:
        return None
    low = name.lower()
    for rx, vendor, platform, cls in _NAME_RE:
        if rx.search(low):
            return vendor, platform, cls
    return None


def classify_bluetooth_device(name, address, rssi=None):
    """Classify one device. Returns dict with vendor/platform/device_class/confidence."""
    result = {
        "name": name or "Unknown",
        "address": address or "",
        "vendor": None,
        "platform": "unknown",
        "device_class": "unknown",
        "confidence": 0.0,
        "rssi": rssi if rssi is not None else -100,
        "distance_m": rssi_to_distance(rssi) if rssi is not None else None,
    }
    nb = classify_by_name(name)
    if nb:
        vendor, platform, cls = nb
        result["vendor"] = vendor
        result["platform"] = platform
        result["device_class"] = cls
        result["confidence"] = 0.95 if vendor else 0.8
        result["classify_source"] = "name"
        return result
    if address and not is_randomized_mac(address):
        vendor = oui_vendor(address)
        if vendor:
            result["vendor"] = vendor
            result["platform"] = VENDOR_PLATFORM.get(vendor, "other")
            result["device_class"] = (
                "phone"
                if result["platform"] == "android"
                else "computer"
                if result["platform"] == "computer"
                else "other"
            )
            result["confidence"] = 0.7
            result["classify_source"] = "oui"
            return result
    result["classify_source"] = "unknown"
    return result


def rssi_to_distance(rssi, tx_power=-59.0, path_loss=2.5):
    """Estimate distance in meters from RSSI (log-distance path loss)."""
    if rssi is None or rssi == 0:
        return None
    ratio = (tx_power - rssi) / (10 * path_loss)
    return round(10 ** ratio, 2)


def distance_description(distance):
    if distance is None or distance < 0:
        return "unknown distance"
    if distance < 1.0:
        return "right next to us"
    if distance < 3.0:
        return "within a few steps"
    if distance < 10.0:
        return "nearby, same room"
    if distance < 30.0:
        return "a bit further away"
    return "quite far away"


def classify_devices(devices):
    """Classify a scan result list -> classified devices + platform counts.

    devices: list of dicts with at least 'name' and 'address' (and optionally 'rssi').
    """
    out = []
    counts = {"ios": 0, "android": 0, "apple": 0, "computer": 0, "audio": 0, "iot": 0, "other": 0, "unknown": 0}
    for d in devices:
        c = classify_bluetooth_device(
            d.get("name", ""), d.get("address", ""), d.get("rssi")
        )
        # existing fields win for distance if the caller already computed them
        if d.get("distance_m") is not None:
            c["distance_m"] = d.get("distance_m")
        if d.get("distance_desc"):
            c["distance_desc"] = d.get("distance_desc")
        else:
            c["distance_desc"] = distance_description(c.get("distance_m"))
        c["paired"] = bool(d.get("paired"))
        out.append(c)
        bucket = c["platform"] if c["platform"] in counts else "other"
        counts[bucket] += 1
    return {"devices": out, "counts": counts}


def format_summary(result):
    """Human-spoken summary of a classify_devices() result."""
    counts = result["counts"]
    ios = counts.get("ios", 0)
    android = counts.get("android", 0)
    total_known = ios + android
    total = len(result["devices"])
    parts = []
    if ios and android:
        parts.append(f"{ios} iPhone{'s' if ios != 1 else ''} and {android} Android phone{'s' if android != 1 else ''}")
    elif ios:
        parts.append(f"{ios} iPhone{'s' if ios != 1 else ''}")
    elif android:
        parts.append(f"{android} Android phone{'s' if android != 1 else ''}")
    if counts.get("computer"):
        parts.append(f"{counts['computer']} laptop{'s' if counts['computer'] != 1 else ''}")
    if counts.get("audio"):
        parts.append(f"{counts['audio']} audio device{'s' if counts['audio'] != 1 else ''}")
    if counts.get("iot"):
        parts.append(f"{counts['iot']} smart-home device{'s' if counts['iot'] != 1 else ''}")
    if counts.get("unknown"):
        parts.append(f"{counts['unknown']} unidentified device{'s' if counts['unknown'] != 1 else ''}")
    if not parts:
        if total == 0:
            return "I don't see any Bluetooth devices nearby right now."
        return f"I can see {total} device{'s' if total != 1 else ''} nearby, but none look like phones."
    return "Around us I can see " + ", ".join(parts) + "."
